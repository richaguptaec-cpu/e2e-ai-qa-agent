from agents.base_agent import BaseAgent
from models.schemas import FinalTestSuite
from prompts.report_prompt import REPORT_PROMPT


class ReportAgent(BaseAgent):

    def generate(
        self,
        user_story,
        acceptance_criteria,
        functional=None,
        security=None,
        session=None,
        performance=None,
        accessibility=None,
        compatibility=None
    ):
        """
        Consolidate test cases generated by the selected
        specialist QA agents.

        Unselected agents may return None and are safely
        excluded from the report generation input.
        """

        functional_data = (
            functional.model_dump_json()
            if functional is not None
            else '{"test_cases": []}'
        )

        security_data = (
            security.model_dump_json()
            if security is not None
            else '{"test_cases": []}'
        )

        session_data = (
            session.model_dump_json()
            if session is not None
            else '{"test_cases": []}'
        )

        performance_data = (
            performance.model_dump_json()
            if performance is not None
            else '{"test_cases": []}'
        )

        accessibility_data = (
            accessibility.model_dump_json()
            if accessibility is not None
            else '{"test_cases": []}'
        )

        compatibility_data = (
            compatibility.model_dump_json()
            if compatibility is not None
            else '{"test_cases": []}'
        )

        prompt = REPORT_PROMPT.format(
            user_story=user_story,
            acceptance_criteria=acceptance_criteria,
            functional=functional_data,
            security=security_data,
            session=session_data,
            performance=performance_data,
            accessibility=accessibility_data,
            compatibility=compatibility_data
        )

        data = self.ask_json(prompt)

        return FinalTestSuite.model_validate(data)
