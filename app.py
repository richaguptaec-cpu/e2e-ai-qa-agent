def display_acceptance_criteria(result):

    """

    Display generated or manually entered acceptance criteria.

    """



    st.subheader("Acceptance Criteria")



    if not result:



        st.info(

            "No acceptance criteria available."

        )



        return



    criteria = result.acceptance_criteria



    if not criteria:



        st.info(

            "No acceptance criteria available."

        )



        return



    for criterion in criteria:



        st.markdown(

            f"\*\*{criterion.id}\*\* — "

            f"{criterion.description}"

        )





