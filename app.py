def display_validation_summary(validated_suite):



    st.subheader(

        "🛡️ QA Validation Summary"

    )



    total_generated = (

        len(validated_suite.test_cases)

        + validated_suite.duplicates_removed

    )



    approved = sum(

        1

        for test in validated_suite.test_cases

        if test.validation_status == "Approved"

    )



    needs_review = sum(

        1

        for test in validated_suite.test_cases

        if test.validation_status == "Needs Review"

    )



    col1, col2, col3, col4 = st.columns(4)



    col1.metric(

        "Generated",

        total_generated

    )



    col2.metric(

        "Duplicates Removed",

        validated_suite.duplicates_removed

    )



    col3.metric(

        "Approved",

        approved

    )



    col4.metric(

        "Needs Review",

        needs_review

    )



    # --------------------------------------------------------

    # Quality Distribution

    # --------------------------------------------------------



    st.markdown(

        "### Quality Distribution"

    )



    excellent = sum(

        1

        for test in validated_suite.test_cases

        if test.quality_status == "Excellent"

    )



    good = sum(

        1

        for test in validated_suite.test_cases

        if test.quality_status == "Good"

    )



    needs_improvement = sum(

        1

        for test in validated_suite.test_cases

        if test.quality_status == "Needs Improvement"

    )



    poor = sum(

        1

        for test in validated_suite.test_cases

        if test.quality_status == "Poor"

    )



    col1, col2, col3, col4 = st.columns(4)



    col1.metric(

        "Excellent",

        excellent

    )



    col2.metric(

        "Good",

        good

    )



    col3.metric(

        "Needs Improvement",

        needs_improvement

    )



    col4.metric(

        "Poor",

        poor

    )





def display_validated_test_suite(validated_suite):



    st.subheader(

        "🧪 Validated QA Test Suite"

    )



    for test in validated_suite.test_cases:



        with st.expander(

            f"{test.test_id} — {test.title}"

        ):



            col1, col2, col3, col4 = st.columns(4)



            with col1:



                st.write(

                    f"\*\*Type:\*\* {test.type}"

                )



            with col2:



                st.write(

                    f"\*\*Priority:\*\* {test.priority}"

                )



            with col3:



                st.write(

                    f"\*\*Quality:\*\* "

                    f"{test.quality_score}/100"

                )



            with col4:



                st.write(

                    f"\*\*Status:\*\* "

                    f"{test.validation_status}"

                )



            st.write(

                f"\*\*Source Agent:\*\* "

                f"{test.source_agent}"

            )



            st.markdown(

                "### Precondition"

            )



            st.write(

                test.precondition

            )



            st.markdown(

                "### Test Steps"

            )



            for index, step in enumerate(

                test.steps,

                start=1

            ):



                st.write(

                    f"{index}. {step}"

                )



            st.markdown(

                "### Expected Result"

            )



            st.success(

                test.expected_result

            )





def display_agent_summary(result):



    st.subheader(

        "🤖 Multi-Agent Generation Summary"

    )



    agents = [

        (

            "Functional Agent",

            result.get("functional")

        ),

        (

            "Security Agent",

            result.get("security")

        ),

        (

            "Session Agent",

            result.get("session")

        ),

        (

            "Performance Agent",

            result.get("performance")

        ),

        (

            "Accessibility Agent",

            result.get("accessibility")

        ),

        (

            "Compatibility Agent",

            result.get("compatibility")

        )

    ]



    # --------------------------------------------------------

    # Only display agents that actually ran

    # --------------------------------------------------------



    active_agents = [

        (

            agent_name,

            agent_result

        )

        for agent_name, agent_result in agents

        if agent_result is not None

    ]



    if not active_agents:



        st.info(

            "No specialist agents were executed."

        )



        return



    columns = st.columns(3)



    for index, (

        agent_name,

        agent_result

    ) in enumerate(active_agents):



        column = columns[index % 3]



        column.metric(

            agent_name,

            len(agent_result.test_cases)

        )





def display_selected_suites(

    selected_suites

):

    """

    Display the selected test suites after generation.

    """



    suite_display_names = {}



    for suites in TEST_SUITE_CATEGORIES.values():



        for suite_id, suite_name in suites:



            suite_display_names[

                suite_id

            ] = suite_name



    st.markdown(

        "### 🎯 Selected Test Suites"

    )



    selected_names = [

        suite_display_names.get(

            suite_id,

            suite_id

        )

        for suite_id in selected_suites

    ]



    if selected_names:



        st.write(

            ", ".join(selected_names)

        )



    else:



        st.write(

            "No test suites selected."

        )





