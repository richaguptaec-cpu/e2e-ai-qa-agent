# MILESTONE 7: PLAYWRIGHT AUTOMATION
# This section is outside the generation button block so it
# remains visible after Streamlit reruns on widget changes.
# ============================================================

st.divider()
st.header("🤖 Playwright Automation Agent")
st.write(
    "Generate automation code from an approved test case, "
    "review the code, and execute it with Pytest."
)

saved_result = st.session_state.get("qa_result")
if not saved_result:
    st.info(
        "Generate and validate a test suite above before starting "
        "Playwright automation."
    )
else:
    validated_suite = saved_result.get("validated_suite")

    if validated_suite is None:
        st.info("The saved result does not contain a validated test suite.")
    elif not validated_suite.test_cases:
        st.info("No approved test cases are available.")
    else:
        test_case_options = {
            f"{test_case.test_id} - {test_case.title}": test_case
            for test_case in validated_suite.test_cases
        }

        selected_test_label = st.selectbox(
            "Select an approved test case",
            options=list(test_case_options.keys()),
            key="automation_test_case",
        )
        selected_test_case = test_case_options[selected_test_label]

        st.subheader("1. Automation Configuration")
        target_url = st.text_input(
            "Target website URL",
            value="https://www.saucedemo.com/",
            key="automation_target_url",
        )
        st.caption("Use only websites you are authorized to test.")

        st.subheader("2. Test Credentials")
        sauce_username = st.text_input(
            "SauceDemo username",
            value="",
            help="Enter a practice account username.",
            key="automation_username",
        )
        sauce_password = st.text_input(
            "SauceDemo password",
            value="",
            type="password",
            help="Credentials are passed to the local test process as environment variables.",
            key="automation_password",
        )

        st.subheader("3. Generate Automation Code")
        if st.button("⚙️ Generate Playwright Code", key="generate_automation_code"):
            try:
                if not target_url.strip():
                    st.error("Enter a target website URL before generating code.")
                    st.stop()

                with st.spinner("Generating Playwright code..."):
                    automation_agent = AutomationAgent()
                    test_case_json = selected_test_case.model_dump_json(indent=2)

                    if "saucedemo.com" in target_url.lower():
                        page_information = (
                            "SauceDemo login page. Username input has placeholder "
                            "'Username'. Password input has placeholder 'Password'. "
                            "The login button is named 'Login'. Successful standard-user "
                            "login navigates to /inventory.html. Read credentials from "
                            "environment variables SAUCEDEMO_USERNAME and "
                            "SAUCEDEMO_PASSWORD."
                        )
                    else:
                        page_information = (
                            "Page details have not been inspected. Do not invent "
                            "selectors or expected behavior. If details are insufficient, "
                            "report what needs manual inspection."
                        )

                    saved_acceptance = st.session_state.get("qa_acceptance_text", "")
                    acceptance_result = saved_result.get("acceptance_criteria")
                    acceptance_for_prompt = (
                        saved_acceptance.strip()
                        or str(acceptance_result or "Not provided")
                    )

                    generated = automation_agent.generate(
                        base_url=target_url.strip(),
                        approved_test_case=test_case_json,
                        user_story=st.session_state.get("qa_user_story", ""),
                        acceptance_criteria=acceptance_for_prompt,
                        page_information=page_information,
                    )
                    saved_path = save_generated_test(
                        code=generated["code"],
                        filename=generated["filename"],
                    )

                    st.session_state["automation_generated_code"] = generated["code"]
                    st.session_state["automation_generated_path"] = str(saved_path)
                    st.session_state["automation_generation_details"] = generated
                    st.session_state.pop("automation_execution_result", None)
                    st.session_state["automation_review_approved"] = False

                st.success("Playwright code generated successfully.")
            except Exception as exc:
                st.error("Playwright code generation failed.")
                st.exception(exc)

        generated_code = st.session_state.get("automation_generated_code")
        if generated_code:
            st.subheader("4. Review Generated Code")
            st.code(generated_code, language="python")

            generation_details = st.session_state.get(
                "automation_generation_details", {}
            )
            assumptions = generation_details.get("assumptions", [])
            manual_review_items = generation_details.get("manual_review_required", [])

            if assumptions:
                st.warning("Assumptions to review")
                for assumption in assumptions:
                    st.write(f"- {assumption}")

            if manual_review_items:
                st.warning("The following items need manual review.")
                for item in manual_review_items:
                    st.write(f"- {item}")

            reviewed = st.checkbox(
                "I have reviewed this generated code and approve running it "
                "against the configured practice/test environment.",
                key="automation_review_approved",
            )

            if st.button(
                "▶️ Execute Approved Test",
                key="execute_automation_test",
                disabled=not reviewed,
            ):
                try:
                    with st.spinner("Running Playwright/Pytest..."):
                        execution_result = run_pytest(
                            test_file=st.session_state["automation_generated_path"],
                            reviewed=reviewed,
                            base_url=target_url,
                            username=sauce_username,
                            password=sauce_password,
                            timeout=120,
                        )
                    st.session_state["automation_execution_result"] = execution_result
                except Exception as exc:
                    st.error(f"Test execution failed: {exc}")
                    st.exception(exc)

            execution_result = st.session_state.get("automation_execution_result")
            if execution_result:
                st.subheader("5. Automation Execution Results")
                status = execution_result.get("status")
                if status == "passed":
                    st.success("Pytest execution passed.")
                elif status == "timed_out":
                    st.warning("Test execution exceeded the timeout.")
                else:
                    st.error("Pytest execution failed.")

                st.write("Exit code:", execution_result.get("return_code"))
                st.text_area(
                    "Pytest output",
                    value=execution_result.get("output", ""),
                    height=300,
                    key="automation_execution_output",
                )
                st.download_button(
                    "Download Generated Python Test",
                    data=generated_code,
                    file_name="test_generated.py",
                    mime="text/x-python",
                    key="download_generated_automation",
                )
